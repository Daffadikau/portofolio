  // ikon yang dibuat Dikau sendiri lewat pixelit — dipakai sebagai gambar,
  // bukan peta pixel, karena hasilnya lebih bagus dari gambar tangan
  const IMAGES = {
    github: 'assets/icons/brand/github.png',
    linkedin: 'assets/icons/brand/linkedin.png',
    spotify: 'assets/icons/brand/spotify.png',
  };
  function render(name, scale = 1) {
    if (!IMAGES[name] && !MAPS[name]) {
      // jangan sampai satu nama salah mematikan seluruh proses render
      console.warn('PixelArt: peta tidak dikenal:', name);
      return document.createElement('span');
    }
    if (IMAGES[name]) {
      const img = document.createElement('img');
      img.src = IMAGES[name];
      img.alt = '';
      img.className = 'px-img';
      img.width = 16 * scale;
      img.height = 16 * scale;
      return img;
    }
    const map = MAPS[name];
    const NS = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(NS, 'svg');
    const h = map.length, w = map[0].length;
    svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
    svg.setAttribute('width', w * scale);
    svg.setAttribute('height', h * scale);
    svg.setAttribute('shape-rendering', 'crispEdges');
    svg.setAttribute('aria-hidden', 'true');
    map.forEach((row, y) => {
      [...row].forEach((ch, x) => {
        if (ch === '.') return;
        const r = document.createElementNS(NS, 'rect');
        r.setAttribute('x', x); r.setAttribute('y', y);
        r.setAttribute('width', 1); r.setAttribute('height', 1);
        r.setAttribute('fill', PALETTE[ch] || '#000');
        svg.appendChild(r);
      });
    });
    return svg;
  }
  // renderStack: gambar beberapa peta berlapis (untuk wardrobe Smoky).
  // Layer wajib berdimensi sama dengan peta dasar; yang tidak cocok dilewati.
  function renderStack(names, scale = 1) {
    const list = names.filter((n) => n && MAPS[n]);
    if (!list.length) return render('cat', scale);
    const base = MAPS[list[0]];
    const NS = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(NS, 'svg');
    const h = base.length, w = base[0].length;
    svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
    svg.setAttribute('width', w * scale);
    svg.setAttribute('height', h * scale);
    svg.setAttribute('shape-rendering', 'crispEdges');
    svg.setAttribute('aria-hidden', 'true');
    list.forEach((name) => {
      const map = MAPS[name];
      if (map.length !== h || map[0].length !== w) return;
      map.forEach((row, y) => {
        [...row].forEach((ch, x) => {
          if (ch === '.') return;
          const r = document.createElementNS(NS, 'rect');
          r.setAttribute('x', x); r.setAttribute('y', y);
          r.setAttribute('width', 1); r.setAttribute('height', 1);
          r.setAttribute('fill', PALETTE[ch] || '#000');
          svg.appendChild(r);
        });
      });
    });
    return svg;
  }

  window.PixelArt = { render, renderStack, MAPS };
